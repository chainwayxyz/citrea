#!/usr/bin/env python3
"""Rebuild and pin one Bitcoin DA guest of one network with SP1's pinned Docker builder.

Each guest version a fork runs is pinned under its own index. The ELF and its constants go to
resources/guests/sp1/<network>/<guest>-<index>.elf and .rs; bin/citrea/src/guests.rs maps them
to forks. To verify the latest pins, run this for each guest with its highest index from a clean
checkout, then `git diff --exit-code resources/guests/sp1`. Earlier indexes were built from
earlier code.
"""

import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
ARTIFACTS = ROOT / "resources/guests/sp1"
NETWORKS = ("mainnet", "testnet", "devnet")
GUESTS = {
    "batch-proof": ("citrea-sp1-batch-proof", "BATCH_PROOF"),
    "light-client-proof": ("citrea-sp1-light-client", "LIGHT_CLIENT_PROOF"),
}
# These change development guest semantics and must not leak into canonical pins.
OVERRIDES = (
    "SKIP_GUEST_BUILD",
    "SEQUENCER_PUBLIC_KEY", "INITIAL_PREV_L2_BLOCK_HASH",
    "L2_GENESIS_ROOT", "BATCH_PROOF_METHOD_ID", "PROVER_DA_PUB_KEY", "SEQUENCER_DA_PUB_KEY",
    *(f"METHOD_ID_UPGRADE_AUTHORITY_DA_PUBLIC_KEY_{i}" for i in range(1, 6)),
)


def pin(network, guest, index):
    env = dict(os.environ, CITREA_NETWORK=network, REPR_GUEST_BUILD="1")
    for name in OVERRIDES:
        env.pop(name, None)
    # The light-client guest build-depends on the batch-proof guest, so building it builds both.
    package, prefix = GUESTS[guest]
    command = ["cargo", "build", "--locked", "-p", package,
               "--message-format=json-render-diagnostics"]
    output = subprocess.check_output(command, cwd=ROOT, env=env, text=True)
    directories = {}
    for line in output.splitlines():
        message = json.loads(line)
        if message.get("reason") == "build-script-executed":
            name = message["package_id"].rsplit("#", 1)[-1].split("@", 1)[0]
            directories[name] = Path(message["out_dir"])
    pinned = f"{guest}-{index}"
    shutil.copyfile(directories[package] / f"{prefix}-bitcoin.elf",
                    ARTIFACTS / network / f"{pinned}.elf")
    methods = (directories[package] / "methods.rs").read_text()
    ids = re.search(rf"{prefix}_BITCOIN_ID: \[u32; 8\] = (\[.*\]);", methods).group(1)
    (ARTIFACTS / network / f"{pinned}.rs").write_text("\n".join([
        "// Generated by tools/pin-sp1-guests.py. Do not edit by hand.",
        f'pub const ELF: &[u8] = include_bytes!("{pinned}.elf");',
        "#[rustfmt::skip]",
        f"pub const ID: [u32; 8] = {ids};",
    ]) + "\n")
    # Match SP1 6.10.0's hash_bytes() and bytes32(): big-endian words and base-2^31 packing.
    # https://github.com/succinctlabs/sp1/blob/d83ed91f96701209613720708f36ffce0e98ed33/crates/hypercube/src/verifier/hashable_key.rs#L20-L80
    words = json.loads(ids)
    native_hex = "".join(f"{word:08x}" for word in words)
    packed = sum(word << (31 * (7 - i)) for i, word in enumerate(words))
    print(f"{network}/{pinned}:\n"
          f"  hash_bytes: 0x{native_hex}\n"
          f"  bytes32:    0x{packed:064x}", flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--network", choices=NETWORKS, required=True)
    parser.add_argument("--guest", choices=GUESTS, required=True)
    parser.add_argument("--index", type=int, required=True,
                        help="pin to write: the guest's highest index to rebuild it, "
                             "or the next one for a fork that changes the guest")
    args = parser.parse_args()
    pin(args.network, args.guest, args.index)


if __name__ == "__main__":
    main()
